package scaffold

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

//go:embed templates/*
var templates embed.FS

type data struct {
	HTTPAddress, GRPCAddress, Title, Provider, Contracts string
	Project, Name, Framework, Version                    string
	HTTP, DB                                             bool
	Transport                                            string
	Modules                                              []Module
}

func render(name string, d data) ([]byte, error) {
	t, err := template.ParseFS(templates, "templates/"+name+".tmpl")
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	if err = t.Execute(&out, d); err != nil {
		return nil, err
	}
	if strings.HasSuffix(name, ".go") {
		return format.Source(out.Bytes())
	}
	return out.Bytes(), nil
}

func New(root, modulePath, frameworkVersion string) (*Plan, error) {
	if err := ValidName(filepath.Base(root)); err != nil {
		return nil, err
	}
	if err := ValidModule(modulePath); err != nil {
		return nil, err
	}
	if frameworkVersion == "" {
		frameworkVersion = Version
	}
	if err := ValidFrameworkVersion(frameworkVersion); err != nil {
		return nil, err
	}
	p := &Plan{Root: root, New: true}
	d := data{Project: modulePath, Framework: Framework, Version: frameworkVersion}
	for _, file := range []string{"go.mod", "main.go", "config/config.go", "README.md", ".env.example", ".gitignore"} {
		name := filepath.Base(file)
		content, err := render(name, d)
		if err != nil {
			return nil, err
		}
		p.Changes = append(p.Changes, Change{Path: file, Data: content})
	}
	m := Manifest{Format: 1, Module: modulePath, FrameworkVersion: frameworkVersion, Modules: []Module{}, Owned: map[string]string{}}
	content, err := registry(m)
	if err != nil {
		return nil, err
	}
	p.Changes = append(p.Changes, Change{Path: "modules/registry_gen.go", Data: content})
	m.Owned["modules/registry_gen.go"] = hash(content)
	if err = p.manifest(m, nil); err != nil {
		return nil, err
	}
	return p, nil
}

func CreateModule(root, name, transport string, db bool) (*Plan, error) {
	if err := ValidName(name); err != nil {
		return nil, err
	}
	if transport != "http" && transport != "none" && transport != "grpc" && transport != "http,grpc" {
		return nil, fmt.Errorf("transport must be http, none, grpc or http,grpc")
	}
	m, old, err := Load(root)
	if err != nil {
		return nil, err
	}
	for _, entry := range m.Modules {
		if entry.Name == name {
			return nil, fmt.Errorf("module %s already exists; files preserved", name)
		}
	}
	p := &Plan{Root: root}
	d := data{Project: m.Module, Framework: Framework, Version: m.FrameworkVersion, Name: name, HTTP: strings.Contains(transport, "http"), DB: db, Transport: transport}
	files := []string{"module.go", "service.go", "service_test.go"}
	if d.HTTP {
		files = append(files, "http/handlers.go", "http/schemas.go", "http/routes.go", "http/openapi.go")
	}
	if db {
		files = append(files, "models.go", "repository.go", "repository_gorm.go")
	}
	for _, file := range files {
		content, e := render("module_"+filepath.Base(file), d)
		if e != nil {
			return nil, e
		}
		p.Changes = append(p.Changes, Change{Path: filepath.Join("modules", name, file), Data: content})
	}
	entry := Module{Name: name, Transport: transport, DB: db}
	if entry.HasGRPC() {
		if err = addRPC(p, &m, entry); err != nil {
			return nil, err
		}
	}
	m.Modules = append(m.Modules, entry)
	sort.Slice(m.Modules, func(i, j int) bool { return m.Modules[i].Name < m.Modules[j].Name })
	if d.HTTP {
		content, e := httpRegistry(m.Module, entry)
		if e != nil {
			return nil, e
		}
		if e = p.owned(&m, filepath.ToSlash(filepath.Join("modules", name, "http_registry_gen.go")), content); e != nil {
			return nil, e
		}
	}
	if db {
		p.Changes = append(p.Changes, Change{Path: filepath.Join("migrations", fmt.Sprintf("%06d_create_%s.up.sql", len(m.Modules), name)), Data: []byte(fmt.Sprintf("CREATE TABLE %s (id INTEGER PRIMARY KEY, message TEXT NOT NULL);\nINSERT INTO %s(id,message) VALUES (1,'%s');\n", name, name, name))})
	}
	content, err := registry(m)
	if err != nil {
		return nil, err
	}
	if err = p.owned(&m, "modules/registry_gen.go", content); err != nil {
		return nil, err
	}
	if err = p.manifest(m, old); err != nil {
		return nil, err
	}
	return p, nil
}

func registry(m Manifest) ([]byte, error) {
	for _, entry := range m.Modules {
		if entry.HasGRPC() {
			return render("registry_rpc_gen.go", data{Project: m.Module, Framework: Framework, Modules: m.Modules, GRPCAddress: m.GRPCAddress})
		}
	}
	return render("registry_gen.go", data{Project: m.Module, Framework: Framework, Modules: m.Modules})
}
func httpRegistry(project string, m Module) ([]byte, error) {
	if len(m.Versions) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by gonex. DO NOT EDIT.\npackage %s\nimport (transport %q\n", m.Name, Framework+"/http")
		if !m.Replace {
			fmt.Fprintf(&b, "legacy %q\n", project+"/modules/"+m.Name+"/http")
		}
		for _, v := range m.Versions {
			fmt.Fprintf(&b, "%s %q\n", v, project+"/modules/"+m.Name+"/http/"+v)
		}
		b.WriteString(")\nfunc registerHTTP(r transport.EndpointRegistrar,s *Service)error{\n")
		if !m.Replace {
			b.WriteString("if err:=legacy.Register(r,s.Message,\"\",\"\");err!=nil{return err}\n")
		}
		for _, v := range m.Versions {
			fmt.Fprintf(&b, "{scope,err:=transport.WithVersion(r,%q,%q);if err!=nil{return err};if err=%s.Register(scope,s.Message,\"\",\"\");err!=nil{return err}}\n", v, m.Prefixes[v], v)
		}
		b.WriteString("return nil\n}\n")
		return format.Source([]byte(b.String()))
	}
	return format.Source([]byte(fmt.Sprintf("// Code generated by gonex. DO NOT EDIT.\npackage %s\nimport (\ntransport %q\nadapter %q\n)\nfunc registerHTTP(r transport.EndpointRegistrar,s *Service)error{return adapter.Register(r,s.Message,\"\",\"\")}\n", m.Name, Framework+"/http", project+"/modules/"+m.Name+"/http")))
}
